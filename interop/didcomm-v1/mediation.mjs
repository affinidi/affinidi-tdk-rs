console.log(`wrote ${requests.length} Credo-built mediation requests`)

// Sanity: every request must round-trip through its own Credo class, or the
// fixture is not what Credo would send.
const requestClasses = {
  mediate_request: DidCommMediationRequestMessage,
  keylist_update_add: DidCommKeylistUpdateMessage,
  keylist_update_remove: DidCommKeylistUpdateMessage,
  status_request: DidCommStatusRequestV2Message,
  delivery_request: DidCommDeliveryRequestV2Message,
  messages_received: DidCommMessagesReceivedV2Message,
}
for (const request of requests) {
  JsonTransformer.fromJSON(request.message, requestClasses[request.name])
}
console.log('self-check: every generated request validates against its Credo class')

// ── Us -> Credo: validate the mediator's replies ────────────────────────────

/** Reply `@type` (either document-URI spelling) -> the Credo class for it. */
const replyClasses = [
  ['coordinate-mediation/1.0/mediate-grant', DidCommMediationGrantMessage],
  ['coordinate-mediation/1.0/mediate-deny', DidCommMediationDenyMessage],
  ['coordinate-mediation/1.0/keylist-update-response', DidCommKeylistUpdateResponseMessage],
  ['messagepickup/2.0/status', DidCommStatusV2Message],
  ['messagepickup/2.0/delivery', DidCommMessageDeliveryV2Message],
]

function classFor(type) {
  const match = replyClasses.find(([suffix]) => type.endsWith(suffix))
  return match?.[1]
}

if (!existsSync(REPLIES_PATH)) {
  console.log('no rust-mediation-replies.json — skipping the us -> Credo direction')
} else {
  const { replies } = JSON.parse(readFileSync(REPLIES_PATH, 'utf8'))
  let failed = 0

  for (const { name, reply } of replies) {
    const type = reply['@type']
    const Class = classFor(type)
    if (!Class) {
      console.error(`  FAILED ${name}: no Credo class matches @type ${type}`)
      failed++
      continue
    }

    try {
      // Validates as well as parses: a wrong member name, wrong casing, a
      // missing required field or an out-of-spec @id all throw here.
      const parsed = JsonTransformer.fromJSON(reply, Class)
      // Re-serialising and re-parsing catches a field Credo dropped silently
      // on the way in — it would vanish rather than round-trip.
      JsonTransformer.fromJSON(parsed.toJSON(), Class)
      console.log(`  ok ${name}: Credo accepts ${type.split('/').slice(-2).join('/')}`)
    } catch (error) {
      console.error(`  FAILED ${name} (${type}): ${error?.message ?? error}`)
      failed++
    }
  }

  console.log(`Credo validated ${replies.length - failed}/${replies.length} mediator replies`)
  if (failed) process.exitCode = 1
}

