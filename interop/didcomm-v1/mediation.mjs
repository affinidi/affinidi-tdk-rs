// Credo conformance for coordinate-mediation 1.0 and message-pickup 2.0.
//
// Run via `run.mjs`. Two halves, mirroring the envelope interop in
// `generate.mjs`:
//
// **Credo -> us.** Builds each request with Credo's *real* message classes and
// writes their JSON to the committed fixtures the mediator's e2e test replays.
// So the requests the mediator is tested against are the ones Credo actually
// emits — field names, decorators and all — rather than our reading of the RFC.
//
// **Us -> Credo.** Reads the replies the mediator produced
// (`rust-mediation-replies.json`, written by the e2e test) and parses each one
// through `JsonTransformer.fromJSON` against the matching Credo class. That
// call *validates*: wrong member name, wrong casing, a missing required field
// or an out-of-spec `@id` all throw. It is the assertion that Credo would
// accept what we send.
//
// This is the layer the envelope interop does not reach. Packing and unpacking
// are already proven against live Credo output in `generate.mjs`; what is
// unproven without this is whether the *messages inside* are shaped the way
// Credo expects.
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { JsonTransformer, utils } from '@credo-ts/core'
import {
  DidCommDeliveryRequestV2Message,
  DidCommKeylistUpdate,
  DidCommKeylistUpdateAction,
  DidCommKeylistUpdateMessage,
  DidCommKeylistUpdateResponseMessage,
  DidCommMediationDenyMessage,
  DidCommMediationGrantMessage,
  DidCommMediationRequestMessage,
  DidCommMessageDeliveryV2Message,
  DidCommMessagesReceivedV2Message,
  DidCommStatusRequestV2Message,
  DidCommStatusV2Message,
} from '@credo-ts/didcomm'

