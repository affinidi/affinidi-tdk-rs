//! Fuzz `unpack` (frame, envelope, signature, decryption and payload decode)
//! with the published Appendix A keys of the specification's `alice` and `bob`,
//! in both directions, so the seeds (the Appendix A messages) open and mutation
//! explores past the signature and AEAD checks' framing. A routed message's
//! next hop is read as well.
#![no_main]

use affinidi_tsp::message::direct::unpack;
use affinidi_tsp::message::routed::next_hop;
use libfuzzer_sys::fuzz_target;

// Published test keys from the TSP specification, Appendix A. They protect
// nothing and must never be used outside tests.
const ALICE_PK_S: [u8; 32] = [
    0x6f, 0x90, 0xc2, 0x05, 0xa0, 0xa1, 0xa9, 0x65, 0x55, 0x18, 0x93, 0xac, 0x19, 0x67, 0x0a, 0xb8,
    0xab, 0x62, 0xd1, 0x22, 0x9f, 0x9b, 0x9d, 0xe9, 0x4d, 0xf3, 0xb0, 0xba, 0x3f, 0xa1, 0x9b, 0xd8,
];
const ALICE_SK_E: [u8; 32] = [
    0xd0, 0x6d, 0x8e, 0x39, 0xb5, 0x90, 0x97, 0x43, 0x73, 0xf5, 0xf4, 0x7c, 0x2f, 0x20, 0x6f, 0xcd,
    0x51, 0x95, 0x2d, 0xec, 0xd4, 0xdf, 0x0b, 0xb9, 0x63, 0xba, 0x5a, 0xc9, 0x32, 0x58, 0xd8, 0x11,
];
const BOB_PK_S: [u8; 32] = [
    0xf9, 0xec, 0xf1, 0x13, 0x6c, 0x90, 0x57, 0xb6, 0xed, 0x8b, 0x7e, 0x0e, 0x7f, 0x3d, 0x42, 0x83,
    0x2f, 0xd8, 0x91, 0xfd, 0xff, 0xb7, 0xaa, 0x1b, 0xdb, 0x37, 0x38, 0x7a, 0xf0, 0x4a, 0x65, 0x2e,
];
const BOB_SK_E: [u8; 32] = [
    0x8f, 0xde, 0x76, 0x0e, 0x5a, 0x44, 0x4b, 0x85, 0x84, 0x69, 0x2a, 0xd8, 0xef, 0x63, 0xd9, 0xc0,
    0xe8, 0xb5, 0x8f, 0x4d, 0xf9, 0x9b, 0xd8, 0x85, 0xc6, 0xc6, 0x61, 0xfc, 0xe2, 0x9f, 0x70, 0xe1,
];

fuzz_target!(|data: &[u8]| {
    for (receiver_sk_e, sender_pk_s) in [(&BOB_SK_E, &ALICE_PK_S), (&ALICE_SK_E, &BOB_PK_S)] {
        if let Ok(unpacked) = unpack(data, receiver_sk_e, sender_pk_s) {
            let _ = next_hop(&unpacked);
        }
    }
});
